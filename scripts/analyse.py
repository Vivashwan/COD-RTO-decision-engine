"""Reproduce every number in the memo.

    python3 scripts/analyse.py      -> reports/findings.md and reports/analysis.json

Needs the model from scripts/train.py (trained on Apr-Aug; September is the test month).
"""
import copy
import json
import os
import sys
from collections import Counter, defaultdict

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from rto import backtest  # noqa: E402
from rto.data import load_orders, split_by_month  # noqa: E402
from rto.economics import Economics  # noqa: E402
from rto.engine import ROOT, Engine  # noqa: E402
from rto.model import is_rto  # noqa: E402

HOLDOUT = "2026-09"
MONTHLY_COD_ORDERS = 3000 * 0.55  # brief: 3,000 orders/month, 55% COD

out = []          # markdown lines
facts = {}        # machine-readable copy


def h(text):
    out.append(f"\n## {text}\n")


def line(text=""):
    out.append(text)


def rate(rows):
    return sum(map(is_rto, rows)) / len(rows) if rows else float("nan")


def table(header, rows):
    line("| " + " | ".join(header) + " |")
    line("|" + "---|" * len(header))
    for r in rows:
        line("| " + " | ".join(str(c) for c in r) + " |")
    line()


def group(rows, key):
    g = defaultdict(list)
    for r in rows:
        g[key(r)].append(r)
    return g


def rs(x):
    return f"₹{x:,.0f}" if x >= 0 else f"-₹{-x:,.0f}"


def main():
    engine = Engine()
    orders, q = load_orders(os.path.join(ROOT, "data", "orders_sample.csv"))
    train, test = split_by_month(orders, HOLDOUT)
    econ = Economics(engine.policy)
    judged = {o["order_id"] + o["order_datetime"].isoformat(): engine.judge(o) for o in orders}
    J = lambda o: judged[o["order_id"] + o["order_datetime"].isoformat()]  # noqa: E731

    line("# Findings and back-test (generated by scripts/analyse.py)")
    line(f"\nData: {q.raw_rows} rows -> {len(orders)} usable COD orders, "
         f"{min(o['order_datetime'] for o in orders):%d %b} to {max(o['order_datetime'] for o in orders):%d %b %Y}. "
         f"Overall RTO rate {rate(orders):.1%}.")
    line(f"Model trained on Apr-Aug ({len(train)} orders), tested on September ({len(test)} orders) "
         "which it never saw.")

    # ------------------------------------------------------------ data quality
    h("Data quality (fixed before anything else)")
    table(["Issue", "Rows"], [
        ["Exact duplicate rows (same order ID, every field identical)", q.exact_duplicates_removed],
        ["Status label variants ('Rto', 'delivered', 'RTO ')", q.status_labels_fixed],
        ["Order still IN_TRANSIT (no outcome, dropped)", q.non_final_status_removed],
        ["Phone in +91 format (normalised)", q.phones_reformatted],
        ["Phone only 9 digits (invalid)", q.phones_invalid],
        ["Pincode missing", q.pincodes_missing],
        ["Order value ₹0", q.zero_value_orders],
        ["Prior RTOs greater than prior orders (capped)", q.prior_rto_exceeds_prior_orders],
    ])
    facts["quality"] = q.__dict__

    # ------------------------------------------------------------ findings
    h("Findings")
    pin_counts = Counter(o["pincode"] for o in orders if o["pincode"])
    one_off = sum(1 for c in pin_counts.values() if c == 1)
    in_5plus = sum(c for c in pin_counts.values() if c >= 5)
    line(f"**1. Pincode history is too thin to act on.** {len(pin_counts)} distinct pincodes; "
         f"{one_off} of them have exactly one order, and only {in_5plus} orders "
         f"({in_5plus / len(orders):.0%}) sit in pincodes with 5+ orders. "
         "The signal lives one level up, in the pincode district (first 3 digits):\n")
    by_p3 = group([o for o in orders if o["pincode"]], lambda o: o["pincode"][:3])
    rows = sorted(((p3, rs_[0]["city"], len(rs_), rate(rs_)) for p3, rs_ in by_p3.items() if len(rs_) >= 30),
                  key=lambda r: -r[3])
    table(["District", "City", "Orders", "RTO rate"],
          [[f"{p}xxx", c, n, f"{r:.0%}"] for p, c, n, r in rows])
    facts["districts"] = [{"pin3": p, "city": c, "n": n, "rto": r} for p, c, n, r in rows]

    addr = group(orders, lambda o: J(o)["address_quality"])
    fake = [o for o in orders if not J(o)["name_plausible"]]
    fake_ok_addr = [o for o in fake if J(o)["address_quality"] != "unusable"]
    line("**2. Bad addresses are the strongest single signal - but even they mostly aren't fraud.**")
    table(["Address", "Orders", "RTO rate", "Delivered anyway"],
          [[k, len(v), f"{rate(v):.0%}", f"{1 - rate(v):.0%}"] for k, v in
           sorted(addr.items(), key=lambda kv: rate(kv[1]))])
    line(f"Hinglish/landmark addresses ('ph krke aana, Govt School ke paas') return at "
         f"{rate(addr['landmark_only']):.0%} - close to average, so they must not be penalised as 'bad'. "
         f"Fake-looking names ({len(fake)} orders) return at {rate(fake):.0%}, but the {len(fake_ok_addr)} "
         f"with a proper address returned at {rate(fake_ok_addr):.0%}: the address does the work, the name barely matters.\n")
    facts["address"] = {k: {"n": len(v), "rto": rate(v)} for k, v in addr.items()}

    cust = group(orders, lambda o: "first order" if o["customer_prior_orders"] == 0 else
                 ("repeat, never refused" if o["customer_prior_rto"] == 0 else
                  ("repeat, refused once" if o["customer_prior_rto"] == 1 else "repeat, refused 2+")))
    line("**3. Past behaviour beats everything else.**")
    table(["Customer", "Orders", "RTO rate"],
          [[k, len(v), f"{rate(v):.0%}"] for k, v in sorted(cust.items(), key=lambda kv: rate(kv[1]))])
    facts["customer"] = {k: {"n": len(v), "rto": rate(v)} for k, v in cust.items()}

    val = group(orders, lambda o: "₹1,500+" if o["order_value"] >= 1500 else "under ₹1,500")
    src = group(orders, lambda o: o["utm_source"])
    src_new = group([o for o in orders if o["customer_prior_orders"] == 0], lambda o: o["utm_source"])
    line(f"**4. Big COD baskets come back more:** {rate(val['₹1,500+']):.0%} RTO at ₹1,500+ "
         f"({len(val['₹1,500+'])} orders) vs {rate(val['under ₹1,500']):.0%} below.\n")
    line(f"**5. Meta ads bring the riskiest first orders:** first-time buyers from Meta ads RTO at "
         f"{rate(src_new['meta_ads']):.0%} vs {rate(src_new['direct']):.0%} for direct traffic "
         f"(all Meta orders: {rate(src['meta_ads']):.0%}, n={len(src['meta_ads'])}).\n")
    cour = group([o for o in orders if o["state"] not in ("Bihar", "Uttar Pradesh", "Madhya Pradesh", "Assam")],
                 lambda o: o["courier"])
    line("**6. Courier matters less than it looks** - outside the four high-RTO states: " + ", ".join(
        f"{k} {rate(v):.0%}" for k, v in sorted(cour.items(), key=lambda kv: rate(kv[1]))) + ".\n")
    facts["value"] = {k: {"n": len(v), "rto": rate(v)} for k, v in val.items()}
    facts["source_first_time"] = {k: {"n": len(v), "rto": rate(v)} for k, v in src_new.items()}

    # ------------------------------------------------------------ economics
    h("Unit economics (from the brief)")
    aov = 649
    V_new = econ.delivered_value(aov, True)
    V_rep = econ.delivered_value(aov, False)
    line(f"- One RTO costs **{rs(econ.rto_loss)}**: ₹65 out + ₹65 back + ₹25 handling + 8% × ₹180 damaged stock.")
    line(f"- One delivered ₹649 order earns **{rs(V_rep)}** (62% margin - ₹65 shipping), "
         f"**{rs(V_new)}** for a first-time buyer once their likely future orders are counted.")
    line(f"- So cancelling only pays when an order is more likely to fail than succeed by a wide margin: "
         f"break-even risk = {econ.cancel_breakeven(aov, False):.0%} (repeat) / "
         f"{econ.cancel_breakeven(aov, True):.0%} (first-time). "
         f"The average COD order is at {rate(orders):.0%}.")
    repeat_share = sum(o["customer_prior_orders"] > 0 for o in orders)
    first_share = len(orders) - repeat_share
    line(f"- Future value of a first-time buyer: repeat orders are {repeat_share} of {len(orders)} "
         f"({repeat_share / len(orders):.0%}), i.e. ~{repeat_share / first_share:.2f} repeat orders per new buyer in steady state; "
         f"× ~₹230 expected contribution per repeat order ≈ ₹75. The ₹300 Meta CAC is already spent when we decide, "
         "so it does not enter the per-order maths - what a cancellation destroys is this order's margin plus that future value.")
    facts["unit"] = {"rto_loss": econ.rto_loss, "V_new": V_new, "V_repeat": V_rep,
                     "breakeven_new": econ.cancel_breakeven(aov, True),
                     "breakeven_repeat": econ.cancel_breakeven(aov, False),
                     "repeat_orders_per_new": repeat_share / first_share}

    # ------------------------------------------------------------ discount maths
    h("How big should the prepaid discount be?")
    line("Moving one COD buyer with risk p to prepaid is worth (p_conv − 4%) × (delivered value + RTO cost), "
         f"where p_conv = {econ.conv_risk} × p because people who accept are less risky than their band. "
         "That is the most a discount can be before it loses money on every conversion:\n")
    rows = []
    for p in (0.15, 0.25, 0.35, 0.50):
        rows.append([f"{p:.0%}", rs(econ.max_sensible_discount(p, aov, True))])
    table(["Order risk", "Max discount that still pays (₹649 first-time order)"], rows)
    line(f"We offer a flat **₹{econ.discount}** (~6% of AOV): it pays for itself from ~25% risk upward, "
         "which is where the nudge band starts. Below that, a discount mostly goes to people who would have "
         "paid anyway. Flat ₹ rather than % because it reads clearly in a WhatsApp message and caps the cost on big baskets.")
    facts["discount_table"] = rows

    # ------------------------------------------------------------ policies on September
    prep_test = backtest.prepare(test, engine)
    prep_train = backtest.prepare(train, engine)
    base_policy = copy.deepcopy(engine.policy)

    def evaluate(policy, prepared):
        _, s = backtest.run(prepared, engine, policy)
        return s

    def policy_with(**kw):
        p = copy.deepcopy(base_policy)
        for path, v in kw.items():
            sect, key = path.split("__")
            p[sect][key] = v
        return p

    ship_all = policy_with(thresholds__nudge_from=101, thresholds__confirm_from=101, thresholds__hold_from=101,
                           rules__hold_if_phone_invalid=False, rules__hold_if_prior_rto_at_least=0,
                           rules__hold_if_fake_name_and_unusable_address=False, rules__confirm_if_address_unusable=False,
                           rules__confirm_if_name_implausible=False, rules__confirm_if_pincode_missing=False,
                           rules__hold_if_zero_value=False, rules__first_time_buyers_max_action="hold")

    # Threshold search on the TRAINING months (outcome-based), then reported on September.
    h("Choosing the thresholds")
    best = None
    for nudge in range(15, 45, 5):
        for confirm in range(nudge, 65, 5):
            for hold in (60, 65, 70, 75, 80, 90, 101):
                pol = policy_with(thresholds__nudge_from=nudge, thresholds__confirm_from=confirm,
                                  thresholds__hold_from=hold)
                net = evaluate(pol, prep_train)["actual"]["net"]
                if best is None or net > best[0]:
                    best = (net, nudge, confirm, hold)
    line(f"Grid search over nudge/confirm/hold thresholds on Apr-Aug orders (using real outcomes): best was "
         f"nudge from {best[1]}%, confirm from {best[2]}%, hold from {best[3]}% "
         f"(net {rs(best[0])} over 5 months). The config ships with nudge {base_policy['thresholds']['nudge_from']} / "
         f"confirm {base_policy['thresholds']['confirm_from']} / hold {base_policy['thresholds']['hold_from']}.")
    facts["grid_best"] = {"net": best[0], "nudge": best[1], "confirm": best[2], "hold": best[3]}
    line("\nThe grid winner is tuned to assumptions we haven't measured yet, so we also check each candidate "
         "when WhatsApp confirmation works worse than assumed (catches 25% of RTOs, loses 15% of genuine buyers):\n")
    rows = []
    for t in [(best[1], best[2], best[3]), (25, 35, 75), (25, 40, 75), (25, 50, 75), (20, 50, 75)]:
        kw = dict(thresholds__nudge_from=t[0], thresholds__confirm_from=t[1], thresholds__hold_from=t[2])
        a = evaluate(policy_with(**kw), prep_train)["actual"]["net"]
        b = evaluate(policy_with(**kw), prep_test)
        c = evaluate(policy_with(**kw, assumptions__confirm_catches_rto_pct=25,
                                 assumptions__confirm_loses_genuine_pct=15), prep_test)["actual"]["net"]
        mark = " **(chosen)**" if t == tuple(base_policy["thresholds"][k] for k in ("nudge_from", "confirm_from", "hold_from")) else ""
        rows.append([f"{t[0]} / {t[1]} / {t[2]}{mark}", rs(a), rs(b["actual"]["net"]), rs(c),
                     f"{b['buckets']['nudge']} / {b['buckets']['confirm']} / {b['buckets']['hold']}"])
    table(["Nudge / confirm / hold from (%)", "Net Apr-Aug", "Net Sept", "Net Sept, weak confirmation",
           "Sept nudge / confirm / hold orders"], rows)
    facts["threshold_candidates"] = rows

    h(f"What each approach would have done to September ({len(test)} COD orders)")
    ops_rows = []
    bad_areas = {p3 for p3, a in engine.model.area.pin3.items() if a["n"] >= 20 and a["raw"] >= 0.45}
    for o, j, s in prep_test:
        ft = o["customer_prior_orders"] == 0
        risky = s["p"] >= 0.40 or (o["pincode"][:3] in bad_areas)
        ops_rows.append(econ.impact_actual("hold" if risky else "ship", is_rto(o) == 1, s["p"], o["order_value"], ft))
    ops = {k: round(sum(r[k] for r in ops_rows)) for k in ("saved", "lost", "cost", "net")}
    ops_cancelled = sum(1 for o, j, s in prep_test if s["p"] >= 0.40 or o["pincode"][:3] in bad_areas)

    def money_optimal():
        rows_ = []
        for o, j, s in prep_test:
            ft = o["customer_prior_orders"] == 0
            a = econ.best_action(s["p"], o["order_value"], ft)
            rows_.append((a, econ.impact_actual(a, is_rto(o) == 1, s["p"], o["order_value"], ft)))
        return Counter(a for a, _ in rows_), {k: round(sum(r[k] for _, r in rows_)) for k in ("saved", "lost", "cost", "net")}

    mo_counts, mo = money_optimal()
    rec_decisions, rec = backtest.run(prep_test, engine, base_policy)
    no_cap = evaluate(policy_with(rules__first_time_buyers_max_action="hold"), prep_test)
    scale = MONTHLY_COD_ORDERS / len(test)

    rows = [
        ["Ship everything (today)", "0 held", rs(0), rs(0), rs(0), rs(0)],
        [f"Ops: cancel if risk ≥40% or area >45% RTO ({len(bad_areas)} districts)", f"{ops_cancelled} cancelled",
         rs(ops["saved"]), rs(ops["lost"]), rs(ops["cost"]), rs(ops["net"])],
        ["Recommended rules", f"{rec['buckets']['hold']} held, {rec['buckets']['confirm']} confirm, {rec['buckets']['nudge']} nudge",
         rs(rec["actual"]["saved"]), rs(rec["actual"]["lost"]), rs(rec["actual"]["cost"]), rs(rec["actual"]["net"])],
        ["Recommended, but score may cancel first-timers", f"{no_cap['buckets']['hold']} held",
         rs(no_cap["actual"]["saved"]), rs(no_cap["actual"]["lost"]), rs(no_cap["actual"]["cost"]), rs(no_cap["actual"]["net"])],
        ["Per-order ₹ optimum (reference)", f"{mo_counts['hold']} held, {mo_counts['confirm']} confirm, {mo_counts['nudge']} nudge",
         rs(mo["saved"]), rs(mo["lost"]), rs(mo["cost"]), rs(mo["net"])],
    ]
    table(["Approach", "Actions", "RTO cost saved", "Genuine margin lost", "Discounts + WhatsApp", "Net vs today"], rows)
    line(f"Scaled to a full month of COD (~{MONTHLY_COD_ORDERS:,.0f} orders, ×{scale:.1f}): recommended ≈ "
         f"**{rs(rec['actual']['net'] * scale)}/month**, Ops rule ≈ **{rs(ops['net'] * scale)}/month**.")
    line(f"\nRecommended buckets in September: " + ", ".join(
        f"{k}: {v} orders ({rec['rto_in_bucket'][k] / v:.0%} actually RTO'd)" for k, v in rec["buckets"].items() if v) + ".")
    facts["september"] = {"ops": ops, "ops_cancelled": ops_cancelled, "recommended": rec, "no_first_time_cap": no_cap,
                          "money_optimal": mo, "money_optimal_counts": dict(mo_counts), "scale": scale,
                          "bad_areas": sorted(bad_areas)}
    rule_counts = Counter(d["rule"].split(":")[0].split(" of ")[0] for d in rec_decisions if d["rule"])
    line("\nRule hits in September: " + ", ".join(f"{k} ({v})" for k, v in rule_counts.most_common()) + ".")
    facts["september_rules"] = dict(rule_counts)

    # ------------------------------------------------------------ sensitivity
    h("How sure are we? (sensitivity of the recommended rules, September)")
    line("Confirmation and nudge results are assumptions until measured. Net ₹ for September under other values:\n")
    rows = []
    for label, kw in [
        ("Base case", {}),
        ("Confirmation catches only 25% of RTOs", {"assumptions__confirm_catches_rto_pct": 25}),
        ("Confirmation loses 15% of genuine buyers", {"assumptions__confirm_loses_genuine_pct": 15}),
        ("Both of the above", {"assumptions__confirm_catches_rto_pct": 25, "assumptions__confirm_loses_genuine_pct": 15}),
        ("Only 5% take the prepaid offer", {"assumptions__nudge_conversion_pct": 5}),
        ("New buyer worth ₹300 more (Marketing's view)", {"assumptions__future_value_first_time_buyer": 300}),
    ]:
        s = evaluate(policy_with(**kw), prep_test)["actual"]
        rows.append([label, rs(s["net"]), rs(s["net"] * scale)])
    table(["Scenario", "Net, September sample", "Net per month (scaled)"], rows)
    facts["sensitivity"] = rows

    engine.reload_policy(base_policy)
    os.makedirs(os.path.join(ROOT, "reports"), exist_ok=True)
    with open(os.path.join(ROOT, "reports", "findings.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    with open(os.path.join(ROOT, "reports", "analysis.json"), "w", encoding="utf-8") as f:
        json.dump(facts, f, indent=1, default=str)
    print("\n".join(out))


if __name__ == "__main__":
    main()
